/** flagcdn.com codes (ISO 3166-1 alpha-2, plus UK home nations). */
const SPECIAL_CODES: Record<string, string> = {
  england: "gb-eng",
  scotland: "gb-sct",
  wales: "gb-wls",
  "northern ireland": "gb-nir",
};

function nationalityKey(name: string): string {
  return name
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

export function nationalityFlagCode(nationality: string): string {
  const key = nationalityKey(nationality);
  if (!key) return "";
  if (SPECIAL_CODES[key]) return SPECIAL_CODES[key];
  const iso = ISO_BY_NATIONALITY[key];
  return iso ? iso.toLowerCase() : "";
}

export function nationalityFlagSrc(nationality: string): string {
  const code = nationalityFlagCode(nationality);
  return code ? `https://flagcdn.com/w80/${code}.png` : "";
}
